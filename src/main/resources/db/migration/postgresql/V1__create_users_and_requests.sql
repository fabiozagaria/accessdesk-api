CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('EMPLOYEE', 'MANAGER'))
);

CREATE TABLE requests (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    software_name VARCHAR(80)  NOT NULL,
    reason        VARCHAR(500) NOT NULL,
    urgency       VARCHAR(255) NOT NULL,
    status        VARCHAR(255) NOT NULL,
    user_id       BIGINT       NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    decided_at    TIMESTAMP(6) WITH TIME ZONE,
    version       INTEGER      NOT NULL,
    CONSTRAINT fk_requests_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_requests_urgency CHECK (urgency IN ('STANDARD', 'URGENT')),
    CONSTRAINT ck_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_requests_user_id ON requests (user_id);
